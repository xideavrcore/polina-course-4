<?php
// Упражнение 4: простейшие программы на PHP

// 1. Присвоить $a = 10, $b = 20 и вывести значения
$a = 10;
$b = 20;
echo "1) a = $a, b = $b<br>";

// 2. Сумма $a и $b → $c, вывести $c
$c = $a + $b;
echo "2) c = $c<br>";

// 3. Увеличить $c в три раза, вывести результат
$c = $c * 3;
echo "3) c * 3 = $c<br>";

// 4. Разделить $c на разность $b и $a, вывести результат
echo "4) c / (b - a) = " . ($c / ($b - $a)) . "<br>";

// 5. Новые переменные: $p = «Программа», $b = «работает»
$p = "Программа";
$b = "работает";
echo "5) p = $p, b = $b<br>";

// 6. Сложить строки через пробел → $result
$result = $p . " " . $b;
echo "6) result = $result<br>";

// 7. Оператор .= - добавить « хорошо»
$result .= " хорошо";
echo "7) result = $result<br>";

// 8. Обмен значениями $q и $w без новых переменных
$q = 5;
$w = 7;
echo "8) до обмена: q = $q, w = $w<br>";
$q = $q + $w;
$w = $q - $w;
$q = $q - $w;
echo "8) после обмена: q = $q, w = $w<br>";
?>
